#!/usr/bin/env node
// Vendors shiny.cov-r/inst/js/discover-bindings.js into this package as a
// generated CommonJS module, so the Playwright adapter evaluates the exact
// same UI-discovery algorithm the R side does, rather than a hand-ported
// copy that could drift from it. Same contract as
// shiny.cov-cypress/scripts/sync-discover-bindings.js.
//
// Run from shiny.cov-playwright/: node scripts/sync-discover-bindings.js
'use strict'

const fs = require('node:fs')
const path = require('node:path')

// Monorepo-relative: this script is a maintainer/dev-time tool that only
// ever runs from within a checkout containing both packages as siblings.
// It is never invoked by an npm consumer of the published package.
const CANONICAL_PATH = path.resolve(__dirname, '..', '..', 'shiny.cov-r', 'inst', 'js', 'discover-bindings.js')
const OUTPUT_PATH = path.resolve(__dirname, '..', 'src', 'vendor', 'discover-bindings-source.js')

const HEADER = '// GENERATED by scripts/sync-discover-bindings.js from shiny.cov-r/inst/js/discover-bindings.js -- do not edit by hand, re-run the sync script instead.\n'

// JSON.stringify() handles the string escaping (quotes, backticks, newlines)
// so the generated module stays valid regardless of what the canonical
// source contains, rather than hand-wrapping it in a template literal.
function renderVendoredModule(source) {
  return HEADER + `module.exports = ${JSON.stringify(source)};\n`
}

function sync() {
  const source = fs.readFileSync(CANONICAL_PATH, 'utf8')
  const rendered = renderVendoredModule(source)
  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true })
  fs.writeFileSync(OUTPUT_PATH, rendered)
  return OUTPUT_PATH
}

if (require.main === module) {
  const written = sync()
  console.log(`Wrote ${written}`)
}

module.exports = { CANONICAL_PATH, OUTPUT_PATH, renderVendoredModule, sync }
